#!/usr/bin/env python3
"""Verify an iOS IPA carries libsmb2's LGPL-2.1 object code.

Why this exists
---------------
libsmb2 is licensed under the GNU Lesser General Public License v2.1. On iOS
it is linked STATICALLY into the app binary, so LGPL-2.1 section 6(a)
applies: the object code of the library must accompany the work, so the user
can modify libsmb2 and relink a modified executable.

The archive that carries it is generated by `ios/libsmb2_build.sh` at build
time and is not checked in. Three things can go wrong, all of them silent:

  * the build script did not run (so no archive exists at all),
  * the build script ran but the packaging step failed,
  * the archive was produced but the Flutter asset declaration in
    `pubspec.yaml` no longer picks it up, so it never reaches the bundle.

None of them break the build. The app would ship, look fine, and quietly
break the license -- the kind of problem that is invisible until a review
asks for the relinking material. This script inspects the BUILT product, so
it catches all three. It runs on Linux, no Mac needed.

Usage
-----
    python3 tool/verify_ipa_libsmb2.py [path/to/App.ipa ...]

With no arguments it looks for `build/ios/ipa/*.ipa` and `DreamPlayer-*.ipa`.
Exits non-zero and prints what is missing when the archive is absent or
incomplete, so it can be used as a CI gate.
"""

from __future__ import annotations

import io
import sys
import zipfile
from pathlib import Path

ASSET_ENTRY = "Payload/Runner.app/flutter_assets/assets/libsmb2-objects/libsmb2-objects.zip"

# Everything the license and the relinking instructions need.
REQUIRED_ENTRIES = (
    "LICENCE-LGPL-2.1.txt",
    "RELINK.txt",
    "source/",
)


def candidate_ipas(explicit: list[str]) -> list[Path]:
    if explicit:
        return [Path(p) for p in explicit]
    found: list[Path] = []
    for pattern in ("build/ios/ipa/*.ipa", "DreamPlayer-*.ipa"):
        found.extend(sorted(Path().glob(pattern)))
    return found


def check_ipa(ipa: Path) -> list[str]:
    problems: list[str] = []
    try:
        with zipfile.ZipFile(ipa) as bundle:
            names = bundle.namelist()
            matches = [n for n in names if n.endswith("libsmb2-objects.zip")]
            if not matches:
                problems.append(
                    f"{ipa}: no libsmb2 object-code archive in the bundle "
                    f"(looked for {ASSET_ENTRY}) -- ios/libsmb2_build.sh must "
                    f"run before the Flutter build, and pubspec.yaml must "
                    f"declare assets/libsmb2-objects/"
                )
                return problems
            entry = matches[0]
            if entry != ASSET_ENTRY:
                problems.append(
                    f"{ipa}: object-code archive is at {entry}, expected "
                    f"{ASSET_ENTRY}"
                )
            data = bundle.read(entry)
            if len(data) < 100000:
                problems.append(
                    f"{ipa}: object-code archive is only {len(data)} bytes -- "
                    f"the packaging step did not really run"
                )
                return problems
            with zipfile.ZipFile(io.BytesIO(data)) as objects:
                inner = objects.namelist()
                objs = [n for n in inner if n.endswith(".o")]
                if len(objs) < 50:
                    problems.append(
                        f"{ipa}: the archive holds {len(objs)} object files, "
                        f"expected the whole libsmb2 library (>=50)"
                    )
                for required in REQUIRED_ENTRIES:
                    if not any(n.startswith(required) for n in inner):
                        problems.append(
                            f"{ipa}: the archive is missing {required}"
                        )
    except zipfile.BadZipFile as e:
        problems.append(f"{ipa}: not a readable zip ({e})")
    return problems


def main() -> int:
    ipas = candidate_ipas(sys.argv[1:])
    if not ipas:
        print("no IPA found -- nothing to verify")
        return 0
    problems: list[str] = []
    for ipa in ipas:
        problems.extend(check_ipa(ipa))
    if problems:
        print("libsmb2 object code: FAILED")
        for p in problems:
            print(f"  - {p}")
        return 1
    print(
        f"libsmb2 object code: OK ({len(ipas)} IPA(s) carry the LGPL-2.1 "
        f"relinking material)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
